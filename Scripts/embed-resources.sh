#!/bin/sh
# Regenerates Sources/TinyTownCore/EmbeddedResources.swift from Resources/.
# Run this after editing anything in Resources/ (including Resources/heiankyo11c/,
# which Scripts/gen-heiankyo11c-atlas.py generates).
set -eu
cd "$(dirname "$0")/.."

out=Sources/TinyTownCore/EmbeddedResources.swift
{
  echo "// GENERATED by Scripts/embed-resources.sh — do not edit by hand."
  echo "// Source: Resources/patterns.png, Resources/tiles.json, Resources/heiankyo11c/*"
  echo ""
  echo "enum EmbeddedResources {"
  printf '    static let patternsPNG = "'
  base64 < Resources/patterns.png | tr -d '\n'
  echo '"'
  printf '    static let tilesJSON = "'
  base64 < Resources/tiles.json | tr -d '\n'
  echo '"'
  printf '    static let heiankyoPNG = "'
  base64 < Resources/heiankyo11c/patterns.png | tr -d '\n'
  echo '"'
  printf '    static let heiankyoJSON = "'
  base64 < Resources/heiankyo11c/tiles.json | tr -d '\n'
  echo '"'
  echo "}"
} > "$out"
echo "wrote $out"
